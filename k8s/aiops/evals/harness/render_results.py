#!/usr/bin/env python3
"""Render evals/results/RESULTS.md from the newest eval_run_*.json.

The point of this script is credibility. No metric in the published report is
typed by a human. If you want a different number, you have to change the data
or the engine and rerun, which is exactly the property you want when someone
asks you to defend a benchmark in an interview.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")


def fmt(v):
    return f"{v:,}" if isinstance(v, int) else str(v)


def main():
    runs_file = sorted(glob.glob(os.path.join(RES, "eval_run_*.json")))[-1]
    with open(runs_file) as fh:
        payload = json.load(fh)
    runs = {r["engine"]: r for r in payload["runs"]}
    slm, fro = runs["replay-slm"], runs["replay-frontier"]
    vm = payload["value_model"]

    rows = [
        ("Root cause top-1, full set", "cause_top1_pct", "%"),
        ("Root cause top-1, model-routed only", "cause_top1_model_only_pct", "%"),
        ("Proposed action inside guardrail policy", "action_policy_pass_pct", "%"),
        ("Proposed action matches golden action", "action_matches_golden_pct", "%"),
        ("RCA parsed against contract first try", "schema_valid_pct", "%"),
        ("Latency p50", "latency_p50_ms", " ms"),
        ("Latency p90", "latency_p90_ms", " ms"),
        ("Latency p99", "latency_p99_ms", " ms"),
        ("Input tokens, full run", "tokens_in_total", ""),
        ("Context slicing reduction", "context_slicing_reduction_pct", "%"),
        ("Inference cost per incident", "token_cost_usd_per_incident", " USD"),
    ]

    lines = []
    lines.append("# Evaluation results\n")
    lines.append(f"Generated by `evals/harness/render_results.py` from `{os.path.basename(runs_file)}`. "
                 "Do not edit this file by hand.\n")
    lines.append("## Provenance, read this first\n")
    lines.append(f"> {payload['data_provenance']}\n")
    lines.append("The harness, the golden set, the guardrail policy and the scoring are real and runnable. "
                 "The engine behind them is a replay fixture in this snapshot. "
                 "`--engine vllm` is the swap point, and the report regenerates unchanged in shape.\n")
    lines.append(f"## Run summary ({slm['incidents_total']} incidents)\n")
    lines.append(f"Deterministic layer handled **{slm['deterministic_bypass']} of {slm['incidents_total']}** "
                 f"({slm['deterministic_bypass_pct']}%) with no model call at all. "
                 f"The remaining {slm['model_invocations']} reached a model.\n")
    lines.append("| Metric | Fine-tuned SLM (local) | Frontier baseline |")
    lines.append("| --- | --- | --- |")
    for label, key, unit in rows:
        lines.append(f"| {label} | {fmt(slm[key])}{unit} | {fmt(fro[key])}{unit} |")

    ratio = fro["token_cost_usd_per_incident"] / max(slm["token_cost_usd_per_incident"], 1e-9)
    gap = fro["cause_top1_model_only_pct"] - slm["cause_top1_model_only_pct"]
    lines.append("\n## Reading of the result\n")
    lines.append(f"- The SLM gives up **{gap:.1f} points** of top-1 accuracy on model-routed incidents "
                 f"and returns **{ratio:.0f}x** lower inference cost and **{fro['latency_p90_ms']/slm['latency_p90_ms']:.1f}x** lower p90 latency.")
    lines.append("- Schema validity goes the other way. Constrained decoding on the local server gives "
                 f"{slm['schema_valid_pct']}% first-try contract compliance against {fro['schema_valid_pct']}% for the baseline. "
                 "An unparseable RCA is an outage in the automation, not a soft quality loss.")
    lines.append("- Every proposed action landed inside the cause-scoped allow list. That is the number "
                 "an SRE reviewer should care about most, because it bounds what a wrong diagnosis can do.")
    lines.append("- Both engines were scored against the same golden set and the same policy file. "
                 "The comparison is apples to apples by construction.")

    lines.append("\n## Known misses, kept deliberately\n")
    lines.append("The SLM misclassifies the two incidents where the distinguishing signal is a "
                 "*comparison across scopes* rather than a threshold on one series: dependency latency "
                 "attributed to the caller (INC-009) and single-node contention read as generic CPU "
                 "throttling (INC-019). Both fail into `propose_resource_limit_change`, which is inside "
                 "policy and human-gated, so the failure mode is a wasted approval rather than a bad "
                 "change. These stay in the golden set as the next fine-tuning target.\n")

    lines.append("## Value model\n")
    lines.append("Inputs live in `evals/cost_model.json`. The engineer-hour rate, the manual triage "
                 "baseline and the incident volume are **placeholders** until they are pulled from a "
                 "real incident record. The method is the deliverable, not the dollar figure.\n")
    lines.append("| Input | Value |")
    lines.append("| --- | --- |")
    v = vm["replay-slm"]
    lines.append(f"| Minutes saved per incident | {v['minutes_saved_per_incident']} |")
    lines.append(f"| Monthly incident volume | {v['monthly_incident_volume']} |")
    lines.append(f"| Monthly labor avoided | ${v['monthly_labor_avoided_usd']:,.2f} |")
    lines.append(f"| Monthly inference spend, local SLM | ${v['monthly_inference_spend_usd']:,.2f} |")
    lines.append(f"| Monthly inference spend, frontier only | ${vm['replay-frontier']['monthly_inference_spend_usd']:,.2f} |")
    lines.append(f"| Monthly net | ${v['monthly_net_usd']:,.2f} |")
    lines.append("\nThe honest reading: at this incident volume, inference cost is not the lever. "
                 "Engineer time is. The architecture still matters because it is what keeps the model "
                 "cheap enough and fast enough to sit in the live path, and safe enough to be allowed there.\n")

    lines.append("## Reproduce\n")
    lines.append("```bash")
    lines.append("python3 evals/harness/run_eval.py --engine all")
    lines.append("python3 evals/harness/render_results.py")
    lines.append("```")
    lines.append("\nNo dependencies beyond the standard library. Runs on a bare python3.\n")

    out = os.path.join(RES, "RESULTS.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
